// Writes src/data/generated/catalog.json, the catalog the site is built from (see src/data/catalog.ts).
// `npm run build` and `npm run dev` run this first.
//
// Sources, in order:
//   1. --file <path> or CATALOG_FILE=<path>: a local catalog file (tests, emergencies);
//   2. --from <origin> or CATALOG_URL=<https://…/api/catalog.json>: the admin portal's public catalog (remote mode);
//   3. otherwise (or CATALOG_SOURCE=snapshot): the committed src/data/catalog.snapshot.json.
// The catalog is validated strictly (src/data/catalog.validate.mjs: every object whitelisted, so a stock count, a
// private note or an unknown field stops the build) and every photo it names must exist in src/assets/img before
// anything is written.
//
// Remote mode (design §2.5, §8):
//   - HTTPS only (plain http only for localhost / 127.0.0.1); 20 s timeout per try, 3 tries; at most 5 MB of JSON.
//   - Uploaded photos (`uploads/<ULID>.jpg`) are downloaded from <origin>/media/uploads/<ULID>.jpg into
//     src/assets/img/uploads/ (gitignored). Each download must be HTTP 200, a JPEG (starts FF D8 FF, ends FF D9),
//     between 100 bytes and 8 MB, and exactly as long as its Content-Length. Good files are kept in
//     node_modules/.astro/beezy-uploads/ (Workers Builds keeps that folder between builds), so only new photos are
//     downloaded. MEDIA_ORIGIN=<origin> takes photos from another host (also for snapshot or file builds that name
//     uploads).
//   - `--save-snapshot` also writes the fetched catalog to src/data/catalog.snapshot.json (`npm run catalog:pull --
//     --from https://beezyhoney.in --save-snapshot`, the monthly refresh and the emergency source).
// Retired products: public/_redirects gets `/shop/<slug>/ /shop/ 301` lines (only while some product is retired; a
// file this script wrote is removed again when none is; a hand-written _redirects is never touched).
//
// Usage: node scripts/sync-catalog.mjs [--file <catalog.json> | --from <origin>] [--save-snapshot]
//        [--out <file>] [--img-dir <dir>] [--cache-dir <dir>] [--redirects <file> | --no-redirects] [--snapshot <file>]
import { copyFileSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { assertCatalog } from '../src/data/catalog.validate.mjs';

const root = path.resolve(import.meta.dirname, '..');
export const SNAPSHOT = path.join(root, 'src/data/catalog.snapshot.json');
const DEFAULTS = {
  out: path.join(root, 'src/data/generated/catalog.json'),
  imgDir: path.join(root, 'src/assets/img'),
  cacheDir: path.join(root, 'node_modules/.astro/beezy-uploads'),
  redirects: path.join(root, 'public/_redirects'),
};

export const MAX_CATALOG_BYTES = 5 * 1024 * 1024;
export const MAX_UPLOAD_BYTES = 8 * 1024 * 1024;
export const MIN_UPLOAD_BYTES = 100;
const TRIES = 3;
const TIMEOUT_MS = 20_000;
export const UPLOAD_RE = /^uploads\/([0-9A-HJKMNP-TV-Z]{26})\.jpg$/;
const LOCAL_HOSTS = ['localhost', '127.0.0.1'];
export const REDIRECTS_MARKER = '# generated by scripts/sync-catalog.mjs (retired products) - do not edit';

export class SyncError extends Error {}
const fail = (msg) => { throw new SyncError(msg); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function readJson(file, what) {
  let text;
  try { text = readFileSync(file, 'utf8'); } catch (e) { fail(`cannot read ${what} (${file}): ${e.message}`); }
  try { return JSON.parse(text); } catch (e) { fail(`${what} is not valid JSON: ${e.message}`); }
}

/** Checks a catalog or media URL: https, or http on localhost / 127.0.0.1; no credentials in it. */
export function checkRemoteUrl(raw, what = 'CATALOG_URL') {
  let u;
  try { u = new URL(String(raw)); } catch { fail(`${what} is not a URL: ${raw}`); }
  if (u.username || u.password) fail(`${what} must not contain a user name or password`);
  const local = LOCAL_HOSTS.includes(u.hostname);
  if (u.protocol !== 'https:' && !(u.protocol === 'http:' && local)) fail(`${what} must use https:// (plain http only for localhost): ${u.origin}`);
  return u;
}

/** fetch with a timeout and retries (network errors and 5xx are retried; 4xx are not). */
async function fetchWithRetry(url, what, fetchImpl = fetch) {
  let last;
  for (let i = 1; i <= TRIES; i++) {
    try {
      const res = await fetchImpl(url, { signal: AbortSignal.timeout(TIMEOUT_MS), redirect: 'error', headers: { accept: 'application/json, image/jpeg;q=0.9' } });
      if (res.status >= 500) throw new Error(`HTTP ${res.status}`);
      return res;
    } catch (e) {
      last = e;
      if (i < TRIES) await sleep(i * 1000);
    }
  }
  fail(`could not fetch ${what} (${url}) after ${TRIES} tries: ${last?.message ?? last}`);
}

async function readCapped(res, max, what) {
  const declared = Number(res.headers.get('content-length') ?? NaN);
  if (Number.isFinite(declared) && declared > max) fail(`${what} is too big (${declared} bytes, at most ${max})`);
  const buf = new Uint8Array(await res.arrayBuffer());
  if (buf.length > max) fail(`${what} is too big (${buf.length} bytes, at most ${max})`);
  return buf;
}

/** Fetches and parses the remote catalog (validation happens in sync()). */
export async function fetchRemoteCatalog(url, fetchImpl = fetch) {
  const u = checkRemoteUrl(url);
  const res = await fetchWithRetry(u.href, 'the catalog', fetchImpl);
  if (res.status !== 200) fail(`the catalog answered HTTP ${res.status} (${u.href})`);
  const type = res.headers.get('content-type') ?? '';
  if (!/^application\/json\b/i.test(type)) fail(`the catalog is not JSON (content-type "${type}")`);
  const bytes = await readCapped(res, MAX_CATALOG_BYTES, 'the catalog');
  try {
    return JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes));
  } catch (e) {
    fail(`the catalog is not valid JSON: ${e.message}`);
  }
}

/** True for a whole JPEG file: starts FF D8 FF, ends FF D9 (a cut-off download fails this). */
export function isCompleteJpeg(bytes) {
  const n = bytes?.length ?? 0;
  return n >= MIN_UPLOAD_BYTES && n <= MAX_UPLOAD_BYTES
    && bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff && bytes[n - 2] === 0xff && bytes[n - 1] === 0xd9;
}

/** Every image path the catalog names. */
export function imagePaths(catalog) {
  const paths = new Set();
  for (const c of catalog.categories) paths.add(c.image);
  for (const p of catalog.products) {
    paths.add(p.photo);
    if (p.card) paths.add(p.card);
    for (const g of p.gallery) paths.add(g.src);
  }
  return [...paths];
}

const isGoodFile = (file) => {
  try { return statSync(file).isFile() && isCompleteJpeg(readFileSync(file)); } catch { return false; }
};

/**
 * Makes sure every `uploads/…` photo the catalog names is in <imgDir>/uploads/: already there, from the cache, or
 * downloaded from <mediaOrigin>/media/uploads/. Returns { present, cached, downloaded }.
 */
export async function syncUploads(catalog, { imgDir, cacheDir, mediaOrigin, fetchImpl = fetch, log = () => {} }) {
  const uploads = imagePaths(catalog).filter((p) => p.startsWith('uploads/'));
  const stats = { present: 0, cached: 0, downloaded: 0 };
  const missing = [];
  for (const p of uploads) {
    const target = path.join(imgDir, p);
    const cached = path.join(cacheDir, path.basename(p));
    if (isGoodFile(target)) { stats.present++; continue; }
    if (isGoodFile(cached)) {
      mkdirSync(path.dirname(target), { recursive: true });
      copyFileSync(cached, target);
      stats.cached++;
      continue;
    }
    missing.push(p);
  }
  if (!missing.length) return stats;
  if (!mediaOrigin) fail(`photos missing from src/assets/img: ${missing.join(', ')} (set MEDIA_ORIGIN=https://beezyhoney.in to download uploaded photos)`);
  const bad = missing.filter((p) => !UPLOAD_RE.test(p));
  if (bad.length) fail(`photos missing from src/assets/img: ${bad.join(', ')} (only uploads/<ULID>.jpg names can be downloaded)`);
  const origin = checkRemoteUrl(mediaOrigin, 'MEDIA_ORIGIN').origin;
  mkdirSync(cacheDir, { recursive: true });
  for (const p of missing) {
    const url = `${origin}/media/${p}`;
    const res = await fetchWithRetry(url, `photo ${p}`, fetchImpl);
    if (res.status !== 200) fail(`photo ${p} answered HTTP ${res.status} (${url})`);
    const type = res.headers.get('content-type') ?? '';
    if (!/^image\/jpeg\b/i.test(type)) fail(`photo ${p} is not a JPEG (content-type "${type}")`);
    const bytes = await readCapped(res, MAX_UPLOAD_BYTES, `photo ${p}`);
    const declared = res.headers.get('content-length');
    if (declared === null || Number(declared) !== bytes.length) fail(`photo ${p}: got ${bytes.length} bytes, the server said ${declared ?? 'nothing'} (cut off?)`);
    if (!isCompleteJpeg(bytes)) fail(`photo ${p} is not a complete JPEG (${bytes.length} bytes)`);
    const cached = path.join(cacheDir, path.basename(p));
    writeFileSync(`${cached}.tmp`, bytes);
    renameSync(`${cached}.tmp`, cached);
    const target = path.join(imgDir, p);
    mkdirSync(path.dirname(target), { recursive: true });
    copyFileSync(cached, target);
    stats.downloaded++;
    log(`  downloaded ${p} (${bytes.length} bytes)`);
  }
  return stats;
}

/** Every image path the catalog names must exist, so a missing photo fails here and not deep inside astro build */
export function checkImages(catalog, imgDir) {
  const missing = imagePaths(catalog).filter((p) => !existsSync(path.join(imgDir, p)));
  if (missing.length) fail(`photos missing from src/assets/img: ${missing.join(', ')}`);
}

/** The _redirects text for retired products, or null when none is retired. */
export function redirectsFor(catalog) {
  const retired = catalog.products.filter((p) => p.status === 'retired').map((p) => p.slug).sort();
  if (!retired.length) return null;
  return `${REDIRECTS_MARKER}\n${retired.map((s) => `/shop/${s}/ /shop/ 301`).join('\n')}\n`;
}

function writeRedirects(catalog, file, log) {
  const text = redirectsFor(catalog);
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (current !== null && !current.startsWith(REDIRECTS_MARKER)) {
    if (text) log(`sync-catalog: ${path.relative(root, file)} was written by hand; not adding the retired-product redirects`);
    return;
  }
  if (text === null) {
    if (current !== null) rmSync(file);
    return;
  }
  if (current !== text) writeFileSync(file, text);
}

function argValue(args, name) {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
}

/** The whole sync. Throws SyncError with a message for the person running the build. */
export async function sync(args = process.argv.slice(2), env = process.env, { fetchImpl = fetch, log = console.log } = {}) {
  const out = path.resolve(argValue(args, '--out') ?? DEFAULTS.out);
  const imgDir = path.resolve(argValue(args, '--img-dir') ?? DEFAULTS.imgDir);
  const cacheDir = path.resolve(argValue(args, '--cache-dir') ?? DEFAULTS.cacheDir);
  const redirects = args.includes('--no-redirects') ? null : path.resolve(argValue(args, '--redirects') ?? DEFAULTS.redirects);
  const snapshotFile = path.resolve(argValue(args, '--snapshot') ?? SNAPSHOT);
  const fileArg = argValue(args, '--file') ?? (env.CATALOG_FILE || undefined);
  const from = argValue(args, '--from');
  const url = from ? `${checkRemoteUrl(from, '--from').origin}/api/catalog.json`
    : env.CATALOG_SOURCE === 'snapshot' ? '' : (env.CATALOG_URL ?? '').trim();

  let catalog;
  let source;
  let remote = null;
  if (fileArg) {
    source = path.resolve(fileArg);
    catalog = readJson(source, 'catalog file');
  } else if (url) {
    remote = checkRemoteUrl(url);
    source = remote.href;
    catalog = await fetchRemoteCatalog(remote.href, fetchImpl);
  } else {
    source = path.relative(root, snapshotFile).split(path.sep).join('/');
    catalog = readJson(snapshotFile, 'the snapshot');
  }

  try { assertCatalog(catalog, source); } catch (e) { fail(e.message); }
  const mediaOrigin = (env.MEDIA_ORIGIN ?? '').trim() || (remote ? remote.origin : '');
  const uploads = await syncUploads(catalog, { imgDir, cacheDir, mediaOrigin, fetchImpl, log });
  checkImages(catalog, imgDir);

  mkdirSync(path.dirname(out), { recursive: true });
  const text = JSON.stringify(catalog, null, 2) + '\n';
  writeFileSync(`${out}.tmp`, text);
  renameSync(`${out}.tmp`, out); // never leave a half-written catalog behind
  if (remote && args.includes('--save-snapshot')) {
    writeFileSync(`${snapshotFile}.tmp`, text);
    renameSync(`${snapshotFile}.tmp`, snapshotFile);
    log(`sync-catalog: saved the fetched catalog as ${path.relative(root, snapshotFile)}`);
  }
  if (redirects) writeRedirects(catalog, redirects, log);

  const live = catalog.products.filter((p) => p.status === 'live').length;
  const photos = uploads.downloaded + uploads.cached + uploads.present;
  log(`sync-catalog: ${source} -> ${path.relative(root, out).split(path.sep).join('/')} (site version ${catalog.siteVersion}, `
    + `${live}/${catalog.products.length} products live, ${catalog.variants.length} packs, ${catalog.batches.length} batches`
    + `${photos ? `, ${photos} uploaded photos (${uploads.downloaded} downloaded)` : ''})`);
  return { catalog, source, uploads };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    await sync();
  } catch (e) {
    console.error(`sync-catalog: ${e instanceof SyncError ? e.message : e?.stack ?? e}`);
    process.exit(1);
  }
}
